def map_fft_coeffs(unit_map: np.ndarray, hks: Sequence[Tuple[int, int]]) -> np.ndarray:
    """Direct complex DFT coefficients at integer fractional-cell indices (h,k).

    The folded unit-cell map array convention is rows=v and columns=u.
    Coefficients are normalized by the number of pixels so amplitudes are stable
    when the grid size changes.
    """
    z = zero_mean(np.asarray(unit_map, dtype=float))
    n_v, n_u = z.shape
    u = np.arange(n_u, dtype=float) / float(n_u)
    v = np.arange(n_v, dtype=float) / float(n_v)
    U, V = np.meshgrid(u, v)
    coeffs = []
    for h, k in hks:
        phase = np.exp(-2j * np.pi * (float(h) * U + float(k) * V))
        coeffs.append(np.sum(z * phase) / float(n_u * n_v))
    return np.asarray(coeffs, dtype=np.complex128)


def coeff_table_for_map(unit_map: np.ndarray, name: str, hks: Sequence[Tuple[int, int]], shell: str) -> pd.DataFrame:
    c = map_fft_coeffs(unit_map, hks)
    rows = []
    for (h, k), val in zip(hks, c):
        gx, gy = hk_to_cartesian_G(h, k)
        rows.append({
            "name": name,
            "shell": shell,
            "h": int(h),
            "k": int(k),
            "q2_120": q2_120(int(h), int(k)),
            "Gx_cart": gx,
            "Gy_cart": gy,
            "coeff_real": float(np.real(val)),
            "coeff_imag": float(np.imag(val)),
            "amplitude": float(abs(val)),
            "power": float(abs(val) ** 2),
            "phase_rad": float(np.angle(val)),
        })
    return pd.DataFrame(rows)


def local_noise_hks() -> List[Tuple[int, int]]:
    out = []
    for h in range(-NOISE_MAX_ABS_INDEX, NOISE_MAX_ABS_INDEX + 1):
        for k in range(-NOISE_MAX_ABS_INDEX, NOISE_MAX_ABS_INDEX + 1):
            q2 = q2_120(h, k)
            if q2 < NOISE_Q2_MIN or q2 > NOISE_Q2_MAX:
                continue
            if q2 in NOISE_EXCLUDED_Q2:
                continue
            out.append((h, k))
    # deterministic unique order
    return sorted(set(out), key=lambda hk: (q2_120(*hk), hk[0], hk[1]))


def tiled_fft_xyz(unit_map: np.ndarray, tile_reps: int = 16, crop_hk: float = 5.5, smooth_sigma_px: float = 0.75) -> pd.DataFrame:
    """Raw-like FFT map from a tiled folded unit cell, as long-format xyz data.

    h/k are the reciprocal indices of the original unit cell. Tiling by tile_reps
    sharpens peaks and makes the sixfold pattern easier to plot.
    """
    z = zero_mean(np.asarray(unit_map, dtype=float))
    tiled = np.tile(z, (int(tile_reps), int(tile_reps)))
    F = np.fft.fftshift(np.fft.fft2(tiled)) / tiled.size
    power = np.abs(F) ** 2
    if smooth_sigma_px and smooth_sigma_px > 0:
        power_smooth = ndimage.gaussian_filter(power, sigma=float(smooth_sigma_px))
    else:
        power_smooth = power
    eps = max(float(np.nanmax(power)) * 1e-14, 1e-300)
    logp = np.log10(power + eps)
    logp_smooth = np.log10(power_smooth + eps)
    n = tiled.shape[0]
    freq = np.fft.fftshift(np.fft.fftfreq(n)) * (n / float(tile_reps))
    H, K = np.meshgrid(freq, freq)
    Gx = H
    Gy = (2.0 * K + H) / math.sqrt(3.0)
    mask = (np.abs(H) <= crop_hk) & (np.abs(K) <= crop_hk)
    return pd.DataFrame({
        "h": H[mask].ravel(),
        "k": K[mask].ravel(),
        "Gx_cart": Gx[mask].ravel(),
        "Gy_cart": Gy[mask].ravel(),
        "log10_power_raw": logp[mask].ravel(),
        "log10_power_smooth_for_plot": logp_smooth[mask].ravel(),
        "power_raw": power[mask].ravel(),
        "power_smooth_for_plot": power_smooth[mask].ravel(),
    })

