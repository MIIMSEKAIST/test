def residualize_to_mean_readout(y: np.ndarray, Z: np.ndarray) -> np.ndarray:
    """Return y evaluated at ensemble-mean Z by removing the centered Z contribution."""
    y = np.asarray(y, dtype=float)
    Z = np.asarray(Z, dtype=float)
    if Z.ndim == 1:
        Z = Z[:, None]
    m = np.isfinite(y) & np.isfinite(Z).all(axis=1)
    out = np.full_like(y, np.nan, dtype=float)
    if m.sum() < max(4, Z.shape[1] + 2):
        return out
    yy = y[m]
    ZZ = Z[m]
    Zmean = np.nanmean(ZZ, axis=0, keepdims=True)
    X = np.column_stack([np.ones(ZZ.shape[0]), ZZ - Zmean])
    coef, *_ = np.linalg.lstsq(X, yy, rcond=None)
    # y_at_mean_readout = y - beta_z @ (Z - meanZ)
    out[m] = yy - (ZZ - Zmean) @ coef[1:]
    return out


