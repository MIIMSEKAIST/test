def main() -> None:
    parser = argparse.ArgumentParser(description="Compute source data for SI Fig. S8-S10 and Tables S2-S5.")
    parser.add_argument("--analysis-dir", "--analysis_dir", dest="analysis_dir", required=True, help="Primary-analysis output directory")
    parser.add_argument("--out-dir", "--out_dir", dest="out_dir", default=None, help="Output directory; defaults to ANALYSIS_DIR/supplementary_source_data")
    parser.add_argument("--map-key", "--map_key", dest="map_key", default=MAP_KEY, help="Array key in motif_analysis_arrays.npz")
    parser.add_argument("--skip-excel", "--skip_excel", dest="skip_excel", action="store_true", help="Do not compile the Excel workbook")
    args = parser.parse_args()

    analysis_dir = Path(args.analysis_dir).expanduser().resolve()
    out_dir = ensure_dir(Path(args.out_dir).expanduser().resolve() if args.out_dir else analysis_dir / OUTPUT_FOLDER_NAME)
    npz_path = analysis_dir / "motif_analysis_arrays.npz"

    print(f"Loading maps from {npz_path} [{args.map_key}] ...")
    maps, names, arrays = load_npz_maps(npz_path, args.map_key)
    coord_df = load_coord_table(analysis_dir, names)
    positions_by_name = load_site_positions(analysis_dir, coord_df, names)

    # Keep map/name order aligned with coord table if possible.
    print(f"Computing Fig. S8 shell detectability for {len(names)} maps ...")
    s8_snr_df = compute_S8(maps, names, out_dir)

    print("Computing real-data readout form-factor fits ...")
    fit_df, coeff_df = compute_real_readout_fits(maps, names, coord_df, positions_by_name, s8_snr_df, out_dir)
    fit_df = add_floor_and_coord_columns(fit_df, coord_df)
    # Update the saved real-fit file after merging metadata.
    fit_save_dir = ensure_dir(out_dir / "readout_form_factor_fits")
    if not fit_df.empty:
        fit_df.to_csv(fit_save_dir / "readout_fit_per_image.csv", index=False, encoding="utf-8-sig")

    print("Computing synthetic validation for Fig. S9 / Table S2 ...")
    compute_synthetic_validation(positions_by_name, out_dir)

    print("Writing Fig. S10 / Table S3 source data ...")
    compute_table_S3_and_S10(fit_df, coeff_df, out_dir)

    print("Writing Table S4 readout-correction correlations ...")
    compute_Table_S4(fit_df, out_dir)

    print("Writing Table S5 component regressions ...")
    compute_Table_S5(fit_df, out_dir)

    print("Writing index and workbook ...")
    write_master_index(out_dir)
    if not args.skip_excel:
        compile_excel_workbook(out_dir)

    print("\nDONE")
    print(f"Output folder: {out_dir}")
    print(f"Index: {out_dir / 'SI_source_data_index.csv'}")
    print(f"README: {out_dir / 'README_SI_source_data.md'}")

if __name__ == "__main__":
    main()
