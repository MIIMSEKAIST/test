def real_space_texture_descriptors(unit_map: np.ndarray) -> Dict[str, float]:
    z = robust_z(unit_map)
    z = zero_mean(z)
    n = z.shape[0]
    yy, xx = np.indices(z.shape)
    coords = (np.arange(n) + 0.5) / n
    U, V = np.meshgrid(coords, coords)
    weights = np.abs(z)
    sw = float(np.sum(weights))
    if sw <= 0:
        sw = 1.0
    uc = float(np.sum(U * weights) / sw)
    vc = float(np.sum(V * weights) / sw)
    du = ((U - uc + 0.5) % 1.0) - 0.5
    dv = ((V - vc + 0.5) % 1.0) - 0.5
    # second moment in square and graphite oblique metrics
    sigma_u = math.sqrt(max(0.0, float(np.sum(weights * du**2) / sw)))
    sigma_v = math.sqrt(max(0.0, float(np.sum(weights * dv**2) / sw)))
    sigma_hex = math.sqrt(max(0.0, float(np.sum(weights * (du**2 + dv**2 - du*dv)) / sw)))

    # autocorrelation central second moment
    F = np.fft.fft2(z)
    ac = np.fft.fftshift(np.real(np.fft.ifft2(np.abs(F)**2)))
    ac = np.maximum(ac - np.nanmin(ac), 0)
    sw_ac = float(np.sum(ac))
    cy, cx = np.array(ac.shape) // 2
    y = (np.arange(n) - cy) / n
    x = (np.arange(n) - cx) / n
    X, Y = np.meshgrid(x, y)
    if sw_ac <= 0:
        ac_sigma_x = ac_sigma_y = ac_sigma_r = np.nan
    else:
        ac_sigma_x = math.sqrt(max(0.0, float(np.sum(ac * X**2) / sw_ac)))
        ac_sigma_y = math.sqrt(max(0.0, float(np.sum(ac * Y**2) / sw_ac)))
        ac_sigma_r = math.sqrt(max(0.0, float(np.sum(ac * (X**2 + Y**2)) / sw_ac)))

    low = ndimage.gaussian_filter(z, sigma=max(1.0, n/12.0))
    hp = z - low
    lap = ndimage.laplace(z)
    gy, gx = np.gradient(z)
    return {
        "second_moment_sigma_u": sigma_u,
        "second_moment_sigma_v": sigma_v,
        "second_moment_sigma_hex": sigma_hex,
        "autocorr_sigma_x": ac_sigma_x,
        "autocorr_sigma_y": ac_sigma_y,
        "autocorr_sigma_r": ac_sigma_r,
        "highpass_energy_fraction": float(np.mean(hp**2) / (np.mean(z**2) + 1e-30)),
        "laplacian_energy": float(np.mean(lap**2)),
        "gradient_energy": float(np.mean(gx**2 + gy**2)),
        "peak_to_peak": float(np.nanmax(z) - np.nanmin(z)),
    }

