def structure_factor_values(
    hks: Sequence[Tuple[int, int]],
    positions: Dict[str, Tuple[float, float]],
    intensities: Sequence[float],
) -> np.ndarray:
    IB, IA, IH = [float(x) for x in intensities]
    vals = []
    for h, k in hks:
        s = 0.0 + 0.0j
        for role, I in zip(("B", "A", "H"), (IB, IA, IH)):
            u, v = positions[role]
            s += I * np.exp(-2j * np.pi * (h * float(u) + k * float(v)))
        vals.append(s)
    return np.asarray(vals, dtype=np.complex128)


def design_matrix_isotropic(hks: Sequence[Tuple[int, int]], positions: Dict[str, Tuple[float, float]], beta: float) -> np.ndarray:
    D = []
    for h, k in hks:
        K_decay = math.exp(-float(beta) * (float(q2_120(h, k)) - 1.0))
        row = []
        for role in ("B", "A", "H"):
            u, v = positions[role]
            row.append(K_decay * np.exp(-2j * np.pi * (h * float(u) + k * float(v))))
        D.append(row)
    return np.asarray(D, dtype=np.complex128)


def solve_real_intensities_complex_lstsq(D: np.ndarray, y: np.ndarray, weights: Optional[np.ndarray] = None) -> Tuple[np.ndarray, float, float]:
    A = np.vstack([D.real, D.imag])
    b = np.concatenate([y.real, y.imag])
    if weights is not None:
        w = np.asarray(weights, dtype=float)
        ww = np.concatenate([w, w])
        A = A * ww[:, None]
        b = b * ww
    finite = np.isfinite(A).all(axis=1) & np.isfinite(b)
    if finite.sum() < 3:
        return np.full(3, np.nan), np.nan, np.nan
    sol, *_ = np.linalg.lstsq(A[finite], b[finite], rcond=None)
    yhat = D @ sol
    rss = float(np.nanmean(np.abs(y - yhat) ** 2))
    denom = float(np.nanmean(np.abs(y) ** 2))
    residual_fraction = rss / denom if denom > 0 else np.nan
    return sol.astype(float), rss, residual_fraction


@dataclass
class IsoFit:
    beta: float
    intensities: np.ndarray
    rss: float
    residual_fraction: float
    fitted: np.ndarray
    beta_railed_low: bool
    beta_railed_high: bool


def fit_isotropic_beta_from_coeffs(
    y: np.ndarray,
    hks_fit: Sequence[Tuple[int, int]],
    positions: Dict[str, Tuple[float, float]],
    weights: Optional[np.ndarray] = None,
    beta_min: float = BETA_MIN,
    beta_max: float = BETA_MAX,
    beta_n: int = BETA_N_GRID,
) -> IsoFit:
    grid = np.linspace(float(beta_min), float(beta_max), int(beta_n))
    best_beta = np.nan
    best_int = np.full(3, np.nan)
    best_rss = np.inf
    best_resid = np.nan
    best_fit = np.full(len(y), np.nan + 1j*np.nan, dtype=np.complex128)
    for beta in grid:
        D = design_matrix_isotropic(hks_fit, positions, float(beta))
        intensities, rss, resid = solve_real_intensities_complex_lstsq(D, y, weights=weights)
        if np.isfinite(rss) and rss < best_rss:
            best_beta = float(beta)
            best_int = intensities
            best_rss = float(rss)
            best_resid = float(resid)
            best_fit = D @ intensities
    return IsoFit(
        beta=best_beta,
        intensities=best_int,
        rss=best_rss,
        residual_fraction=best_resid,
        fitted=best_fit,
        beta_railed_low=bool(np.isfinite(best_beta) and abs(best_beta - beta_min) <= BETA_CAP_TOL),
        beta_railed_high=bool(np.isfinite(best_beta) and abs(best_beta - beta_max) <= BETA_CAP_TOL),
    )


def fit_isotropic_beta(unit_map: np.ndarray, positions: Dict[str, Tuple[float, float]], hks_fit: Sequence[Tuple[int, int]] = FIT_SHELL_HK, weights: Optional[np.ndarray] = None) -> IsoFit:
    y = map_fft_coeffs(unit_map, hks_fit)
    return fit_isotropic_beta_from_coeffs(y, hks_fit, positions, weights=weights)


def beta_to_gaussian_widths(beta: float) -> Dict[str, float]:
    if not np.isfinite(beta) or beta < 0:
        return {"sigma_frac_from_beta": np.nan, "fwhm_frac_from_beta": np.nan, "sigma_nm_from_beta": np.nan, "fwhm_nm_from_beta": np.nan}
    sigma_frac = math.sqrt(float(beta) / (2.0 * math.pi ** 2))
    fwhm_frac = 2.0 * math.sqrt(2.0 * math.log(2.0)) * sigma_frac
    return {
        "sigma_frac_from_beta": sigma_frac,
        "fwhm_frac_from_beta": fwhm_frac,
        "sigma_nm_from_beta": sigma_frac * GRAPHITE_LATTICE_A_NM,
        "fwhm_nm_from_beta": fwhm_frac * GRAPHITE_LATTICE_A_NM,
    }


def hk_to_g_vec(h: int | float, k: int | float) -> np.ndarray:
    gx, gy = hk_to_cartesian_G(h, k)
    return np.asarray([gx, gy], dtype=float)


def design_matrix_anisotropic(hks: Sequence[Tuple[int, int]], positions: Dict[str, Tuple[float, float]], Q: np.ndarray) -> np.ndarray:
    first_vals = []
    for h, k in FIRST_SHELL_HK:
        g = hk_to_g_vec(h, k)
        first_vals.append(float(g @ Q @ g))
    first_mean = float(np.mean(first_vals))
    D = []
    for h, k in hks:
        g = hk_to_g_vec(h, k)
        decay = float(g @ Q @ g) - first_mean
        K_decay = math.exp(-decay)
        row = []
        for role in ("B", "A", "H"):
            u, v = positions[role]
            row.append(K_decay * np.exp(-2j * np.pi * (h * float(u) + k * float(v))))
        D.append(row)
    return np.asarray(D, dtype=np.complex128)


def params_to_Q(params: Sequence[float]) -> np.ndarray:
    p0, p1, p2 = [float(x) for x in params]
    l00 = math.exp(np.clip(p0, -12, 6))
    l10 = p1
    l11 = math.exp(np.clip(p2, -12, 6))
    L = np.asarray([[l00, 0.0], [l10, l11]], dtype=float)
    return L @ L.T


def Q_to_outputs(Q: np.ndarray) -> Dict[str, float]:
    vals, vecs = np.linalg.eigh(Q)
    order = np.argsort(vals)
    vals = np.asarray(vals, dtype=float)[order]
    vecs = np.asarray(vecs, dtype=float)[:, order]
    lam_min, lam_max = float(vals[0]), float(vals[1])
    mean_decay = 0.5 * (lam_min + lam_max)
    eta = (lam_max - lam_min) / (lam_max + lam_min) if (lam_max + lam_min) > 0 else np.nan
    vmax_vec = vecs[:, 1]
    angle_deg = math.degrees(math.atan2(float(vmax_vec[1]), float(vmax_vec[0])))
    angle_deg = ((angle_deg + 90.0) % 180.0) - 90.0
    beta_equiv = (4.0 / 3.0) * mean_decay
    return {
        "anisotropic_Q_a": float(Q[0, 0]),
        "anisotropic_Q_b": float(2.0 * Q[0, 1]),
        "anisotropic_Q_c": float(Q[1, 1]),
        "anisotropic_lambda_min": lam_min,
        "anisotropic_lambda_max": lam_max,
        "anisotropic_mean_decay": mean_decay,
        "anisotropic_width_beta_equiv": beta_equiv,
        "anisotropic_magnitude_eta": eta,
        "anisotropic_orientation_deg": angle_deg,
    }


def isotropic_beta_to_initial_params(beta: float) -> np.ndarray:
    beta = max(float(beta), 1e-6) if np.isfinite(beta) else 0.5
    q = max(3.0 * beta / 4.0, 1e-9)
    L = np.linalg.cholesky(np.eye(2) * q)
    return np.asarray([math.log(L[0, 0]), L[1, 0], math.log(L[1, 1])], dtype=float)


def fit_anisotropic_from_coeffs(y: np.ndarray, hks_fit: Sequence[Tuple[int, int]], positions: Dict[str, Tuple[float, float]], beta_start: float) -> Dict[str, object]:
    def objective(params: np.ndarray) -> float:
        Q = params_to_Q(params)
        D = design_matrix_anisotropic(hks_fit, positions, Q)
        _, rss, _ = solve_real_intensities_complex_lstsq(D, y)
        if not np.isfinite(rss):
            return 1e99
        return float(rss)
    x0 = isotropic_beta_to_initial_params(beta_start)
    try:
        res = minimize(objective, x0, method="Nelder-Mead", options={"maxiter": 600, "xatol": 1e-8, "fatol": 1e-12})
        Q = params_to_Q(res.x)
        D = design_matrix_anisotropic(hks_fit, positions, Q)
        intensities, rss, resid = solve_real_intensities_complex_lstsq(D, y)
        fitted = D @ intensities
        out = Q_to_outputs(Q)
        out.update({
            "anisotropic_fit_success": bool(res.success),
            "anisotropic_fit_message": str(res.message),
            "anisotropic_rss": float(rss),
            "anisotropic_residual_fraction": float(resid),
            "anisotropic_fit_I_B": float(intensities[0]),
            "anisotropic_fit_I_A": float(intensities[1]),
            "anisotropic_fit_I_H": float(intensities[2]),
            "anisotropic_fitted_coefficients": fitted,
        })
        return out
    except Exception as exc:
        return {"anisotropic_fit_success": False, "anisotropic_fit_message": str(exc)}


def fit_anisotropic(unit_map: np.ndarray, positions: Dict[str, Tuple[float, float]], beta_start: float, hks_fit: Sequence[Tuple[int, int]] = FIT_SHELL_HK) -> Dict[str, object]:
    y = map_fft_coeffs(unit_map, hks_fit)
    return fit_anisotropic_from_coeffs(y, hks_fit, positions, beta_start)


def Q_from_beta_eta_phi(beta_equiv: float, eta: float, phi_deg: float) -> np.ndarray:
    """Build anisotropic Q matrix with a beta-equivalent mean decay and axis anisotropy eta."""
    mean_decay = 0.75 * float(beta_equiv)  # inverse of beta_equiv=(4/3)*mean_decay
    eta = float(eta)
    lam_max = mean_decay * (1.0 + eta)
    lam_min = mean_decay * (1.0 - eta)
    phi = math.radians(float(phi_deg))
    R = np.asarray([[math.cos(phi), -math.sin(phi)], [math.sin(phi), math.cos(phi)]], dtype=float)
    return R @ np.diag([lam_min, lam_max]) @ R.T

