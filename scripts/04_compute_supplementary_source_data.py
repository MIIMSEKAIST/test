def compile_excel_workbook(out_dir: Path) -> None:
    xlsx_path = out_dir / "SI_S8_S10_TableS2_S5_source_data.xlsx"
    csvs = sorted([p for p in out_dir.rglob("*.csv") if p.name != "SI_source_data_index.csv"])
    with pd.ExcelWriter(xlsx_path, engine="openpyxl") as writer:
        pd.read_csv(out_dir / "SI_source_data_index.csv").to_excel(writer, sheet_name="index", index=False)
        used = {"index"}
        for p in csvs:
            try:
                df = pd.read_csv(p)
            except Exception:
                continue
            # Excel row limit guard.
            if len(df) > 1_000_000:
                continue
            stem = p.stem
            # Prefix with folder initials to avoid duplicate sheet names.
            folder = p.parent.name
            sheet = f"{folder[:6]}_{stem[:22]}"[:31]
            base = sheet
            j = 1
            while sheet in used:
                suffix = f"_{j}"
                sheet = (base[:31-len(suffix)] + suffix)[:31]
                j += 1
            used.add(sheet)
            df.to_excel(writer, sheet_name=sheet, index=False)

