def representative_site_positions(positions_by_name: Dict[str, Dict[str, Tuple[float,float]]]) -> Dict[str, Tuple[float,float]]:
    if not positions_by_name:
        # Fallback to a simple diagonal default.
        return {"B": (0.0, 0.0), "A": (2.0/3.0, 2.0/3.0), "H": (1.0/3.0, 1.0/3.0)}
    roles = {"B": [], "A": [], "H": []}
    for d in positions_by_name.values():
        for r in roles:
            if r in d:
                roles[r].append(d[r])
    out = {}
    for r, vals in roles.items():
        if not vals:
            continue
        arr = np.asarray(vals, dtype=float)
        # circular mean in unit interval
        u_angle = np.exp(2j*np.pi*arr[:,0])
        v_angle = np.exp(2j*np.pi*arr[:,1])
        u = (np.angle(np.mean(u_angle))/(2*np.pi)) % 1.0
        v = (np.angle(np.mean(v_angle))/(2*np.pi)) % 1.0
        out[r] = (float(u), float(v))
    if not {"B","A","H"}.issubset(out):
        return {"B": (0.0, 0.0), "A": (2.0/3.0, 2.0/3.0), "H": (1.0/3.0, 1.0/3.0)}
    return out


