def load_npz_maps(npz_path: Path, map_key: str) -> Tuple[np.ndarray, List[str], Dict[str, np.ndarray]]:
    if not npz_path.exists():
        raise FileNotFoundError(f"NPZ file not found: {npz_path}")
    data = np.load(npz_path, allow_pickle=True)
    keys = list(data.keys())
    if map_key not in keys:
        raise KeyError(f"MAP_KEY={map_key!r} not found in {npz_path}. Available keys: {keys}")
    maps = np.asarray(data[map_key], dtype=float)
    if maps.ndim != 3:
        raise ValueError(f"{map_key} must have shape (n_images, grid, grid), got {maps.shape}")
    if "names" in keys:
        names = [str(x) for x in data["names"].tolist()]
    else:
        names = [f"image_{i:04d}" for i in range(maps.shape[0])]
    arrays = {k: data[k] for k in keys}
    return maps, names, arrays


def load_coord_table(analysis_dir: Path, names: Sequence[str]) -> pd.DataFrame:
    path = analysis_dir / "orthogonal_motif_coordinates_site_currents.csv"
    if path.exists():
        df = pd.read_csv(path)
        if "name" not in df.columns:
            raise ValueError(f"{path} does not contain a 'name' column.")
        return df
    warnings.warn(f"Coordinate table not found: {path}. Some outputs will be missing.")
    return pd.DataFrame({"name": list(names), "short_name": list(names)})


def load_site_positions(analysis_dir: Path, coord_df: pd.DataFrame, names: Sequence[str]) -> Dict[str, Dict[str, Tuple[float, float]]]:
    site_path = analysis_dir / "per_image_BAH_site_positions.csv"
    positions: Dict[str, Dict[str, Tuple[float, float]]] = {}
    if site_path.exists():
        df = pd.read_csv(site_path)
        required = {"name", "site", "u", "v"}
        if not required.issubset(df.columns):
            raise ValueError(f"{site_path} must contain columns {required}")
        for nm, g in df.groupby("name"):
            d: Dict[str, Tuple[float, float]] = {}
            for _, r in g.iterrows():
                site = str(r["site"])
                if site in {"B", "A", "H"}:
                    d[site] = (float(r["u"]), float(r["v"]))
            if {"B", "A", "H"}.issubset(d):
                positions[str(nm)] = d
    elif {"B_u_used", "B_v_used", "A_u_used", "A_v_used", "H_u_used", "H_v_used"}.issubset(coord_df.columns):
        for _, r in coord_df.iterrows():
            nm = str(r["name"])
            positions[nm] = {
                "B": (float(r["B_u_used"]), float(r["B_v_used"])),
                "A": (float(r["A_u_used"]), float(r["A_v_used"])),
                "H": (float(r["H_u_used"]), float(r["H_v_used"])),
            }
    else:
        warnings.warn("No per-image B/A/H positions found. Readout form-factor fits require site positions.")
    missing = [nm for nm in names if nm not in positions]
    if missing:
        warnings.warn(f"Site positions missing for {len(missing)} images. These images will be skipped in readout fits.")
    return positions


