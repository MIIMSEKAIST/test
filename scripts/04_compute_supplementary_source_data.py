def synthetic_map_from_coeffs(hks: Sequence[Tuple[int, int]], coeffs: np.ndarray, n: int = SYNTH_GRID_N) -> np.ndarray:
    u = np.arange(n, dtype=float) / float(n)
    v = np.arange(n, dtype=float) / float(n)
    U, V = np.meshgrid(u, v)
    z = np.zeros((n, n), dtype=np.complex128)
    for (h, k), c in zip(hks, coeffs):
        z += c * np.exp(2j * np.pi * (float(h) * U + float(k) * V))
    return np.real(z)


def site_intensities_from_cAH_cbeta(c_AH: float, c_beta: float, common: float = 0.0) -> np.ndarray:
    # I = common*[1,1,1] + c_AH*(1,1,-2)/sqrt(6) + c_beta*(-1,1,0)/sqrt(2)
    return np.asarray([
        common + c_AH / math.sqrt(6.0) - c_beta / math.sqrt(2.0),
        common + c_AH / math.sqrt(6.0) + c_beta / math.sqrt(2.0),
        common - 2.0 * c_AH / math.sqrt(6.0),
    ], dtype=float)  # order: A, B, H


def convert_A_B_H_to_B_A_H(I_A_B_H: np.ndarray) -> np.ndarray:
    IA, IB, IH = [float(x) for x in I_A_B_H]
    return np.asarray([IB, IA, IH], dtype=float)


