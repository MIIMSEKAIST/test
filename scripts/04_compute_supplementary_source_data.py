def safe_float(x) -> float:
    try:
        y = float(x)
        return y if np.isfinite(y) else np.nan
    except Exception:
        return np.nan


def robust_z(a: np.ndarray) -> np.ndarray:
    arr = np.asarray(a, dtype=float)
    med = np.nanmedian(arr)
    mad = np.nanmedian(np.abs(arr - med))
    scale = 1.4826 * mad
    if not np.isfinite(scale) or scale <= 1e-15:
        scale = np.nanstd(arr)
    if not np.isfinite(scale) or scale <= 1e-15:
        scale = 1.0
    return (arr - med) / scale


def zero_mean(a: np.ndarray) -> np.ndarray:
    arr = np.asarray(a, dtype=float)
    return arr - np.nanmean(arr)


def q2_120(h: int, k: int) -> int:
    """Squared reciprocal radius for the 120-degree direct-cell convention."""

    return int(h * h + h * k + k * k)


def hk_to_cartesian_G(h: int | float, k: int | float) -> Tuple[float, float]:
    """Cartesian reciprocal coordinates for the 120-degree direct cell."""
    h = float(h)
    k = float(k)
    return h, (2.0 * k + h) / math.sqrt(3.0)


def circular_axis_angle_diff_deg(a: float, b: float) -> float:
    """Absolute axis angle difference in degrees for a 180-degree-periodic principal axis."""
    d = ((float(a) - float(b) + 90.0) % 180.0) - 90.0
    return abs(d)


def spearman_safe(x, y) -> Tuple[float, float, int]:
    x = pd.to_numeric(pd.Series(x), errors="coerce").to_numpy(dtype=float)
    y = pd.to_numeric(pd.Series(y), errors="coerce").to_numpy(dtype=float)
    m = np.isfinite(x) & np.isfinite(y)
    if m.sum() < 4:
        return np.nan, np.nan, int(m.sum())
    r = spearmanr(x[m], y[m])
    return float(r.correlation), float(r.pvalue), int(m.sum())


def pearson_safe(x, y) -> Tuple[float, float, int]:
    x = pd.to_numeric(pd.Series(x), errors="coerce").to_numpy(dtype=float)
    y = pd.to_numeric(pd.Series(y), errors="coerce").to_numpy(dtype=float)
    m = np.isfinite(x) & np.isfinite(y)
    if m.sum() < 4:
        return np.nan, np.nan, int(m.sum())
    r = pearsonr(x[m], y[m])
    return float(r.statistic), float(r.pvalue), int(m.sum())


def bootstrap_spearman_ci(x, y, nboot: int = BOOTSTRAP_N, seed: int = BOOTSTRAP_SEED) -> Tuple[float, float, float, float, int]:
    x = pd.to_numeric(pd.Series(x), errors="coerce").to_numpy(dtype=float)
    y = pd.to_numeric(pd.Series(y), errors="coerce").to_numpy(dtype=float)
    m = np.isfinite(x) & np.isfinite(y)
    x = x[m]
    y = y[m]
    n = int(x.size)
    if n < 4:
        return np.nan, np.nan, np.nan, np.nan, n
    rho, pval, _ = spearman_safe(x, y)
    rng = np.random.default_rng(seed)
    idx = np.arange(n)
    boots = np.empty(nboot, dtype=float)
    for b in range(nboot):
        ii = rng.choice(idx, size=n, replace=True)
        boots[b], _, _ = spearman_safe(x[ii], y[ii])
    return rho, pval, float(np.nanpercentile(boots, 2.5)), float(np.nanpercentile(boots, 97.5)), n


def linear_regression_centered(x, y) -> Dict[str, float]:
    x = pd.to_numeric(pd.Series(x), errors="coerce").to_numpy(dtype=float)
    y = pd.to_numeric(pd.Series(y), errors="coerce").to_numpy(dtype=float)
    m = np.isfinite(x) & np.isfinite(y)
    if m.sum() < 4:
        return {"n": int(m.sum()), "slope": np.nan, "intercept": np.nan, "r2": np.nan,
                "x_mean": np.nan, "x_std": np.nan, "standardized_displacement": np.nan}
    xx = x[m]
    yy = y[m]
    X = np.column_stack([np.ones_like(xx), xx])
    coef, *_ = np.linalg.lstsq(X, yy, rcond=None)
    yhat = X @ coef
    ss_res = float(np.sum((yy - yhat) ** 2))
    ss_tot = float(np.sum((yy - np.mean(yy)) ** 2))
    r2 = 1.0 - ss_res / ss_tot if ss_tot > 0 else np.nan
    x_std = float(np.std(xx, ddof=1)) if xx.size > 1 else np.nan
    return {
        "n": int(xx.size),
        "intercept": float(coef[0]),
        "slope": float(coef[1]),
        "r2": float(r2),
        "x_mean": float(np.mean(xx)),
        "x_std": x_std,
        "standardized_displacement": float(coef[1] * x_std) if np.isfinite(x_std) else np.nan,
    }


def bootstrap_linear_regression_ci(x, y, nboot: int = BOOTSTRAP_N, seed: int = BOOTSTRAP_SEED) -> Dict[str, float]:
    x = pd.to_numeric(pd.Series(x), errors="coerce").to_numpy(dtype=float)
    y = pd.to_numeric(pd.Series(y), errors="coerce").to_numpy(dtype=float)
    m = np.isfinite(x) & np.isfinite(y)
    x = x[m]
    y = y[m]
    n = int(x.size)
    if n < 4:
        return {
            "slope_ci95_low": np.nan, "slope_ci95_high": np.nan,
            "standardized_displacement_ci95_low": np.nan, "standardized_displacement_ci95_high": np.nan,
            "r2_ci95_low": np.nan, "r2_ci95_high": np.nan,
        }
    rng = np.random.default_rng(seed)
    idx = np.arange(n)
    slopes = []
    disps = []
    r2s = []
    for _ in range(nboot):
        ii = rng.choice(idx, size=n, replace=True)
        d = linear_regression_centered(x[ii], y[ii])
        slopes.append(d["slope"])
        disps.append(d["standardized_displacement"])
        r2s.append(d["r2"])
    return {
        "slope_ci95_low": float(np.nanpercentile(slopes, 2.5)),
        "slope_ci95_high": float(np.nanpercentile(slopes, 97.5)),
        "standardized_displacement_ci95_low": float(np.nanpercentile(disps, 2.5)),
        "standardized_displacement_ci95_high": float(np.nanpercentile(disps, 97.5)),
        "r2_ci95_low": float(np.nanpercentile(r2s, 2.5)),
        "r2_ci95_high": float(np.nanpercentile(r2s, 97.5)),
    }

